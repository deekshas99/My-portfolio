"""Generate small panel images while preserving the original lightbox assets."""
import json
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
public = root / "public"
manifest = {}
for p in sorted(p for folder in (public / "aurora", public / "case-studies") for p in folder.rglob("*") if p.suffix.lower() in {".png",".jpg",".jpeg",".webp"}):
    with Image.open(p) as im:
        w,h=im.size
        if max(w,h)<=1600: continue
        relative=p.relative_to(public)
        candidates=[]
        for edge in (1280,2400):
            scale=min(1,edge/max(w,h))
            nw,nh=max(1,round(w*scale)),max(1,round(h*scale))
            if candidates and candidates[-1]["width"]==nw: continue
            if scale==1: dest=p
            else:
                dest=public/"case-study-previews"/relative.parent/f"{relative.stem}-{edge}.webp"
                dest.parent.mkdir(parents=True,exist_ok=True)
                im.convert("RGBA" if "A" in im.getbands() or "transparency" in im.info else "RGB").resize((nw,nh),Image.Resampling.LANCZOS).save(dest,"WEBP",quality=92,method=5,alpha_quality=100)
            candidates.append({"src":"/"+dest.relative_to(public).as_posix(),"width":nw,"height":nh})
        manifest["/"+relative.as_posix()]=candidates
(root/"src/caseStudyImagePreviews.mjs").write_text("// Generated by scripts/generate-case-study-previews.py.\nexport const CASE_STUDY_PREVIEWS = "+json.dumps(manifest,indent=2)+";\n")
print("Generated previews for",len(manifest),"images")
